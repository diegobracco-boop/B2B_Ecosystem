INNER JOIN hoteles_dimension hd
ON CAST(adv.oidhotel AS VARCHAR) = hd.hotel_id
LEFT JOIN hoteles_wrapper hw on adv.oidhotel = CAST(hw.oid AS VARCHAR)
LEFT JOIN gb_por_hotel gh ON CAST(adv.oidhotel AS VARCHAR) = gh.hotel_id
LEFT JOIN reviews_por_hotel_nolatam rh ON CAST(adv.oidhotel AS VARCHAR) = rh.hotel_id
CROSS JOIN maximos_globales mg
WHERE CAST(adv.requestdate_date AS DATE) >= DATE '2026-03-30'
AND CAST(adv.requestdate_date AS DATE) >= date_add('day', 14, hd.fecha_creacion)
)
SELECT
*,
(0.3 * COALESCE(gb_b2b_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado, 0.0)) as peso_hotel_nolatam_v1,
(0.3 * COALESCE(gb_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado_nolatam, 0.0)) as peso_hotel_nolatam_v2,
(
(0.3 * COALESCE(gb_b2b_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado, 0.0))
* peso_es_latam
* CASE
WHEN Distribucion = '2' THEN 0.8
WHEN Distribucion = '2-2' THEN 0.2
ELSE 1.0
END
) AS peso_total_no_latam_b2b,
(
es_adverso_incentivos
* (0.3 * COALESCE(gb_b2b_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado, 0.0))
* peso_es_latam
* CASE
WHEN Distribucion = '2' THEN 0.8
WHEN Distribucion = '2-2' THEN 0.2
ELSE 1.0
END
) AS peso_adverso_no_latam_b2b,
(
(0.3 * COALESCE(gb_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado_nolatam, 0.0))
* peso_es_latam
* CASE
WHEN Distribucion = '2' THEN 0.8
WHEN Distribucion = '2-2' THEN 0.2
ELSE 1.0
END
) AS peso_total_no_latam_b2b_v2,
(
es_adverso_incentivos
* (0.3 * COALESCE(gb_normalizado, 0.0) + 0.7 * COALESCE(reviews_normalizado_nolatam, 0.0))
* peso_es_latam
* CASE
WHEN Distribucion = '2' THEN 0.8
WHEN Distribucion = '2-2' THEN 0.2
ELSE 1.0
END
) AS peso_adverso_no_latam_b2b_v2

FROM base_calculo
